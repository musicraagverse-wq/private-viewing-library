/**
 * Resolve one raw label to its canonical + home. Returns null for dropped
 * (junk) labels. Unknown labels pass through as-is under the caller's
 * fallback home, so new source labels keep showing up instead of vanishing.
 */
export function resolveTag(
  raw: string,
  fallbackHome: TagHome = "trope"
): { canonical: string; home: TagHome } | null {
  const key = raw.trim().toLowerCase();
  if (!key || TAG_DROPS.has(key)) return null;
  const canonical = TAG_ALIASES[key] ?? raw.trim();
  const home = TAG_HOME[canonical] ?? fallbackHome;
  return { canonical, home };
}

/** Canonicalize a raw label list: resolve, drop junk, dedupe by canonical. */
export function canonicalizeTagList(
  list: string[],
  fallbackHome: TagHome = "trope"
): { canonical: string; home: TagHome }[] {
  const seen = new Set<string>();
  const out: { canonical: string; home: TagHome }[] = [];
  for (const raw of list) {
    const r = resolveTag(raw, fallbackHome);
    if (!r || seen.has(r.canonical)) continue;
    seen.add(r.canonical);
    out.push(r);
  }
  return out;
}

/** Raw spellings to LIKE-match when browsing a canonical label. */
export function rawLabelsFor(canonical: string): string[] {
  return RAW_LABELS_FOR[canonical] ?? [canonical.toLowerCase()];
}
